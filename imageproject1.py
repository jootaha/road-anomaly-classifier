import matplotlib.pyplot as plt

def run_single_inference(image_path, model_path='models/roadguard_svm_pipeline.pkl'):
    """Processes a single image and prints out class and confidence scores."""
    if not os.path.exists(image_path):
        print(f"Error: Image path '{image_path}' does not exist.")
        return

    # 1. Load the trained model pipeline
    model = joblib.load(model_path)

    # 2. Replicate the strict Preprocessing Pipeline from Step 2
    img_raw = cv2.imread(image_path)
    img_gray = cv2.cvtColor(img_raw, cv2.COLOR_BGR2GRAY)
    img_resized = cv2.resize(img_gray, (128, 128))
    img_blurred = cv2.GaussianBlur(img_resized, (3, 3), 0)

    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    img_clahe = clahe.apply(img_blurred)

    sharpen_kernel = np.array([[-1,-1,-1], [-1, 9,-1], [-1,-1,-1]])
    img_preprocessed = cv2.filter2D(img_clahe, -1, sharpen_kernel)

    # 3. Replicate HOG Feature Extraction parameters from Step 3
    fd = hog(img_preprocessed,
             orientations=9,
             pixels_per_cell=(16, 16),
             cells_per_block=(2, 2),
             block_norm='L2-Hys',
             visualize=False,
             feature_vector=True).reshape(1, -1) # Reshape for single prediction

    # 4. Run prediction and probability score estimation
    pred_class_idx = model.predict(fd)[0]
    probabilities = model.predict_proba(fd)[0]

    # Class mapping setup
    classes = {0: 'POTHOLE', 1: 'DEBRIS'}
    prediction_text = classes[pred_class_idx]
    confidence = probabilities[pred_class_idx] * 100

    # Print clean formatted CLI output exactly as requested
    print(f"Image      : {os.path.basename(image_path)}")
    print(f"Prediction : {prediction_text}")
    print(f"Confidence : {confidence:.1f}%")
    print(f"Proba      : {{pothole: {probabilities[0]*100:.1f}%, debris: {probabilities[1]*100:.1f}%}}\n")

    # Simple plot visualizer
    plt.figure(figsize=(4, 4))
    plt.imshow(cv2.cvtColor(img_raw, cv2.COLOR_BGR2RGB))
    plt.title(f"{prediction_text} ({confidence:.1f}%)")
    plt.axis('off')
    plt.show()

def run_batch_inference(folder_path, model_path='models/roadguard_svm_pipeline.pkl'):
    """Processes a directory of image files and generates a summary breakdown."""
    if not os.path.exists(folder_path):
        print(f"Error: Folder path '{folder_path}' does not exist.")
        return

    model = joblib.load(model_path)
    classes = {0: 'POTHOLE', 1: 'DEBRIS'}

    # Supported web and camera extensions
    valid_extensions = ('.jpg', '.jpeg', '.png', '.bmp')
    files = [f for f in os.listdir(folder_path) if f.lower().endswith(valid_extensions)]

    pothole_count = 0
    debris_count = 0

    print(f"Starting batch prediction processing on folder: '{folder_path}'")
    print("-" * 50)

    for filename in files:
        full_path = os.path.join(folder_path, filename)
        try:
            # Quick preprocessing and feature extraction loop
            img = cv2.imread(full_path, cv2.IMREAD_GRAYSCALE)
            img = cv2.resize(img, (128, 128))
            img = cv2.GaussianBlur(img, (3, 3), 0)
            img = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8)).apply(img)
            img = cv2.filter2D(img, -1, np.array([[-1,-1,-1], [-1, 9,-1], [-1,-1,-1]]))

            fd = hog(img, orientations=9, pixels_per_cell=(16, 16),
                     cells_per_block=(2, 2), block_norm='L2-Hys',
                     visualize=False, feature_vector=True).reshape(1, -1)

            pred_idx = model.predict(fd)[0]
            conf = model.predict_proba(fd)[0][pred_idx] * 100

            print(f"{filename} → {classes[pred_idx]} ({conf:.1f}%)")

            if pred_idx == 0:
                pothole_count += 1
            else:
                debris_count += 1
        except Exception:
            pass

    print("-" * 50)
    print(f"Summary: {pothole_count} potholes | {debris_count} debris | {len(files)} total processed")

