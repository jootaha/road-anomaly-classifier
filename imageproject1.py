def extract_hog_features(input_dir):
    print(f"Extracting HOG features from '{input_dir}'...")

    features = []
    labels = []

    # Class mapping as defined in the problem statement
    # Class 0: Pothole, Class 1: Debris
    class_mapping = {'pothole': 0, 'debris': 1}

    # Grab all our preprocessed images
    filepaths = glob(os.path.join(input_dir, "*", "pre_*"))
    processed_count = 0

    for filepath in filepaths:
        # Read the preprocessed image in grayscale
        img = cv2.imread(filepath, cv2.IMREAD_GRAYSCALE)
        if img is None:
            continue

        # Figure out if this is a pothole or debris based on the folder name
        class_name = os.path.basename(os.path.dirname(filepath))
        label = class_mapping.get(class_name)

        if label is None:
            continue

        # Extract HOG using the STRICT parameters from the project brief
        fd = hog(img,
                 orientations=9,
                 pixels_per_cell=(16, 16),
                 cells_per_block=(2, 2),
                 block_norm='L2-Hys',
                 visualize=False,
                 feature_vector=True)

        features.append(fd)
        labels.append(label)
        processed_count += 1

    # Convert lists to NumPy arrays for scikit-learn
    X = np.array(features)
    y = np.array(labels)

    print(f"Extraction complete! Processed {processed_count} images.")
    print(f"Feature matrix shape (X): {X.shape}")
    print(f"Labels shape (y): {y.shape}")

    return X, y

