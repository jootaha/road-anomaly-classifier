import os
import cv2
import numpy as np
from glob import glob

def preprocess_images(input_dir, output_dir, img_size=(128, 128)):
    print(f"Reading raw images from '{input_dir}'...")
    os.makedirs(output_dir, exist_ok=True)

    # Setup CLAHE (Contrast Limited Adaptive Histogram Equalization)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))

    # Setup a standard sharpening kernel
    sharpen_kernel = np.array([[-1,-1,-1],
                               [-1, 9,-1],
                               [-1,-1,-1]])

    # Grab all files in the subdirectories
    filepaths = glob(os.path.join(input_dir, "*", "*.*"))
    processed_count = 0

    for filepath in filepaths:
        try:
            # 1. Read image directly in grayscale
            img = cv2.imread(filepath, cv2.IMREAD_GRAYSCALE)

            # Skip if the file wasn't a valid image file
            if img is None:
                continue

            # 2. Resize strictly to 128x128 as defined in the project brief
            img_resized = cv2.resize(img, img_size)

            # 3. Noise removal via Gaussian Blur
            img_blurred = cv2.GaussianBlur(img_resized, (3, 3), 0)

            # 4. Apply CLAHE for histogram equalization
            img_clahe = clahe.apply(img_blurred)

            # 5. Apply Sharpening kernel
            img_sharpened = cv2.filter2D(img_clahe, -1, sharpen_kernel)

            # Determine class folder (pothole or debris)
            class_name = os.path.basename(os.path.dirname(filepath))
            save_dir = os.path.join(output_dir, class_name)
            os.makedirs(save_dir, exist_ok=True)

            # Save the processed image
            filename = os.path.basename(filepath)
            save_path = os.path.join(save_dir, f"pre_{filename}")

            # Write to disk
            cv2.imwrite(save_path, img_sharpened)
            processed_count += 1

        except Exception as e:
            # Silently handle any corrupted image files from the web scraper
            pass

    print(f"Success! Preprocessed {processed_count} valid images and saved them to '{output_dir}'.")

# Execute Step 2
